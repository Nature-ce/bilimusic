/// 把繁体字逐字转成简体，未收录的字符原样保留。
String toSimplified(String input) {
  if (input.isEmpty) {
    return input;
  }
  final StringBuffer buffer = StringBuffer();
  for (final String char in input.split('')) {
    buffer.write(_traditionalToSimplified[char] ?? char);
  }
  return buffer.toString();
}
